#!/usr/bin/env node
// Run from any directory: node scripts/generate-calendar.mjs
// Requires a Node.js distribution with ICU's Chinese calendar data.
import { writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const DAY = 86400000;
const formatter = new Intl.DateTimeFormat('en-US-u-ca-chinese', {
  timeZone: 'UTC', year: 'numeric', month: 'numeric', day: 'numeric',
});
if (formatter.resolvedOptions().calendar !== 'chinese') {
  throw new Error('ICU Chinese calendar is required');
}
const months = [];
for (let time = Date.UTC(1999, 0, 1, 12); time < Date.UTC(2101, 0, 1, 12); time += DAY) {
  const parts = Object.fromEntries(formatter.formatToParts(time).map(({ type, value }) => [type, value]));
  if (!/^\d+$/.test(parts.day ?? '')) { throw new Error(`Invalid Chinese day at ${time}`); }
  if (Number(parts.day) !== 1) { continue; }
  const match = /^(\d{1,2})(bis)?$/.exec(parts.month ?? '');
  if (!match || !/^\d{4}$/.test(parts.relatedYear ?? '')) {
    throw new Error(`Unexpected ICU Chinese date: ${JSON.stringify(parts)}`);
  }
  months.push({
    start: Math.floor(time / DAY), year: Number(parts.relatedYear),
    month: Number(match[1]), leap: Boolean(match[2]),
  });
}
const starts = [];
const years = [];
for (let year = 1999; year <= 2099; year += 1) {
  const indices = months.flatMap((month, index) => month.year === year ? [index] : []);
  if (indices.length !== 12 && indices.length !== 13) { throw new Error(`Incomplete lunar year ${year}`); }
  let packed = 0;
  let leapMonth = 0;
  let expectedMonth = 1;
  for (let slot = 0; slot < indices.length; slot += 1) {
    const index = indices[slot];
    const month = months[index];
    const next = months[index + 1];
    if (!next) { throw new Error(`Missing month after ${year}/${month.month}`); }
    const length = next.start - month.start;
    if (length !== 29 && length !== 30) { throw new Error(`Invalid month length ${length} in ${year}`); }
    if (month.leap) {
      if (leapMonth !== 0 || month.month !== expectedMonth - 1 || slot === 0) {
        throw new Error(`Invalid leap month sequence in ${year}`);
      }
      leapMonth = month.month;
    } else {
      if (month.month !== expectedMonth) { throw new Error(`Invalid month sequence in ${year}`); }
      expectedMonth += 1;
    }
    packed |= (length - 29) << slot;
  }
  if (expectedMonth !== 13 || (indices.length === 13) !== (leapMonth !== 0)) {
    throw new Error(`Invalid complete year ${year}`);
  }
  starts.push(months[indices[0]].start);
  years.push(packed | (leapMonth << 13));
}
// Two Number arrays: 202 entries for 101 lunar years, not a per-day table.
// Lower 13 bits: month lengths (0 = 29, 1 = 30); upper bits: leap month (0 = none).
const rows = values => {
  const result = [];
  for (let i = 0; i < values.length; i += 10) { result.push(`        ${values.slice(i, i + 10).join(', ')}`); }
  return result.join(',\n');
};
const source = `// Generated by scripts/generate-calendar.mjs; do not edit by hand.
// ICU Chinese calendar; Gregorian coverage 2000-01-01 through 2099-12-31.
// Lunar years 1999..2099; STARTS uses days since 1970-01-01.
module LunarData {
    var STARTS = [
${rows(starts)}
    ];
    var YEARS = [
${rows(years)}
    ];
}
`;
const destination = fileURLToPath(new URL('../source/LunarData.mc', import.meta.url));
await mkdir(fileURLToPath(new URL('../source/', import.meta.url)), { recursive: true });
await writeFile(destination, source, 'utf8');
console.log(`Generated ${destination}: ${starts.length} lunar years, ${Buffer.byteLength(source)} source bytes; ICU ${process.versions.icu}`);
