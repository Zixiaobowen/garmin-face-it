#!/usr/bin/env python3
"""Generate manifest and target resource mappings from the verified device matrix."""
import json
import os
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
NS = "http://www.garmin.com/xml/connectiq"
ET.register_namespace("iq", NS)


def write_configuration(targets, destination):
    destination.mkdir(parents=True, exist_ok=True)
    prefix = Path(os.path.relpath(ROOT, destination))
    ids = [t["ciq_product_id"] for t in targets]
    if len(ids) != len(set(ids)) or not all(t["watchface_supported"] for t in targets):
        raise ValueError("Device matrix must contain unique supported Watch Face targets")
    manifest = ET.Element(f"{{{NS}}}manifest", {"version": "3"})
    app = ET.SubElement(manifest, f"{{{NS}}}application", {
        "id": "9d182df86c2d48938ce2c9795678f668", "type": "watchface", "name": "@Strings.AppName",
        "entry": "ReferenceFaceApp", "launcherIcon": "@Drawables.LauncherIcon", "minApiLevel": "1.4.0"})
    products = ET.SubElement(app, f"{{{NS}}}products")
    for product in ids:
        ET.SubElement(products, f"{{{NS}}}product", {"id": product})
    permissions = ET.SubElement(app, f"{{{NS}}}permissions")
    for permission in ("UserProfile", "SensorHistory", "ComplicationSubscriber"):
        ET.SubElement(permissions, f"{{{NS}}}uses-permission", {"id": permission})
    languages = ET.SubElement(app, f"{{{NS}}}languages")
    for language in ("eng", "zhs", "zht"):
        ET.SubElement(languages, f"{{{NS}}}language").text = language
    ET.SubElement(app, f"{{{NS}}}barrels")
    ET.indent(manifest)
    (destination / "manifest.xml").write_text(ET.tostring(manifest, encoding="unicode") + "\n")
    fonts = {208: "small", 218: "small", 240: "240", 260: "260", 280: "280",
             360: "360", 390: "390", 416: "416", 454: "454", 215: "small", 205: "compact"}
    jungle = ["# Generated by scripts/configure.py from docs/compatibility.json", "project.manifest = manifest.xml",
              f"base.sourcePath = {prefix / 'source'};{prefix / 'profiles/mip'};{prefix / 'tests'}",
              f"base.resourcePath = {prefix / 'resources'};{prefix / 'resources-fonts/280'}", ""]
    for target in targets:
        device = target["ciq_product_id"]
        width = int(target["screen_resolution"].split(" x ")[0])
        tech = "amoled" if "AMOLED" in target["screen_technology"] else "mip"
        jungle.extend([f"{device}.sourcePath = {prefix / 'source'};{prefix / ('profiles/' + tech)};{prefix / 'tests'}",
                       f"{device}.resourcePath = {prefix / 'resources'};{prefix / ('resources-fonts/' + fonts[width])}"])
        api = tuple(int(part) for part in target["api_level_compatible_page"].split("."))
        excluded = []
        if api < (3, 2):
            excluded.append("onDeviceSettings")
        if api < (4, 1):
            excluded.append("propertyValidation")
        if excluded:
            jungle.append(f"{device}.excludeAnnotations = {';'.join(excluded)}")
        jungle.append("")
    (destination / "monkey.jungle").write_text("\n".join(jungle))
    return ids


def main():
    targets = json.loads((ROOT / "docs/compatibility.json").read_text())["targets"]
    ids = write_configuration(targets, ROOT)
    print(f"Configured {len(ids)} official targets: {', '.join(ids)}")


if __name__ == "__main__":
    main()
